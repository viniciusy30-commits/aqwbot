def disasm(code):
    r=R(code); out=[]
    while r.p<len(code):
        pos=r.p; op=r.u8(); args=()
        if op in S24:
            v=r.u8()|r.u8()<<8|r.u8()<<16
            if v&0x800000: v-=1<<24
            args=(v,)
        elif op==0x1B:
            def s24():
                v=r.u8()|r.u8()<<8|r.u8()<<16
                return v-(1<<24) if v&0x800000 else v
            d=s24(); c=r.u30(); args=(d,[s24() for _ in range(c+1)])
        elif op in U30: args=(r.u30(),)
        elif op in (0x24,0x65): args=(r.u8(),)
        elif op in U30U30: args=(r.u30(),r.u30())
        elif op==0xEF: args=(r.u8(),r.u30(),r.u8(),r.u30())
        elif op in NAMES: pass
        else: raise Exception('op %x at %d'%(op,pos))
        out.append((pos,op,args))
    return out
def fmt(a,ins,abcp):
    res=[]
    for pos,op,args in ins:
        n=NAMES.get(op,'?')
        ex=''
        if op in (0x46,0x4F,0x4C,0x4A,0x5D,0x5E,0x60,0x66,0x61,0x68,0x6A,0x59,0x80,0x86,0xB2): ex='  ;'+abcp.mname(a,args[0])
        if op==0x2C: ex='  ;"%s"'%abcp.s(a,args[0])
        res.append('%4d %s %s%s'%(pos,n,' '.join(map(str,args)),ex))
    return res
